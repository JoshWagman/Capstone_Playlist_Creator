        with st.spinner("Searching Spotify's Database..."):
            real_tracks = get_real_recommendations(genre, danceability, energy, tempo)
            st.session_state.playlist_data = pd.DataFrame(real_tracks)
            st.success(f"Found {len(real_tracks)} songs matching your vibe!")
