CLIENT_ID = 'YOUR_CLIENT_ID_HERE'
CLIENT_SECRET = 'YOUR_CLIENT_SECRET_HERE'
REDIRECT_URI = 'http://localhost:8501'

# --- Page Configuration ---
st.set_page_config(page_title="Music Matcher", page_icon="🎧", layout="wide")


# --- AUTHENTICATION SETUP ---
def get_spotify_client():
    if CLIENT_ID == 'YOUR_CLIENT_ID_HERE':
        return None  # User hasn't set keys yet

    scope = "playlist-modify-public user-library-read"
    auth_manager = SpotifyOAuth(
        client_id=CLIENT_ID,
        client_secret=CLIENT_SECRET,
        redirect_uri=REDIRECT_URI,
        scope=scope,
        cache_path=".spotify_cache"
    )

    # If not authenticated, this will trigger the login flow
    if not auth_manager.validate_token(auth_manager.cache_handler.get_cached_token()):
        st.sidebar.warning("⚠️ Please log in to Spotify")
        auth_url = auth_manager.get_authorize_url()
        st.sidebar.link_button("Log in with Spotify", auth_url)

        # Check if we were redirected back with a code
        query_params = st.query_params
        if "code" in query_params:
            auth_manager.get_access_token(query_params["code"])
            st.rerun()
        return None

    return spotipy.Spotify(auth_manager=auth_manager)


# Initialize Spotify
sp = get_spotify_client()


# --- HELPER: REAL RECOMMENDATIONS ---
def get_real_recommendations(genre, dance, energy, tempo, limit=12):
    if not sp:
        return []  # Return empty if no login

    # Get numeric values
    seed_genres = [genre.lower()]

    try:
        results = sp.recommendations(
            seed_genres=seed_genres,
            target_danceability=dance,
            target_energy=energy,
            target_tempo=tempo,
            limit=limit
        )

        tracks = []
        for track in results['tracks']:
            tracks.append({
                "Artist": track['artists'][0]['name'],
                "Song Title": track['name'],
                "URI": track['uri'],  # Critical for adding to playlist
                "Preview": track['preview_url'],
                "Genre": genre,
                "Danceability": dance,  # API doesn't return these in simple view, so we assume match
                "Energy": energy
            })
        return tracks
    except Exception as e:
        st.error(f"Spotify API Error: {e}")
        return []


