    st.dataframe(st.session_state.playlist_data[['Artist', 'Song Title', 'Genre']], use_container_width=True)

    if st.button("Add to Spotify Library", icon="🎧"):
        if sp:
            try:
                user_id = sp.me()['id']
                # 1. Create Playlist
                playlist = sp.user_playlist_create(
                    user=user_id,
                    name=f"{genre.capitalize()} Vibe Mix",
                    public=True,
                    description=f"Generated by AI. Dance: {danceability}, Energy: {energy}"
                )

                # 2. Add Tracks
                track_uris = st.session_state.playlist_data['URI'].tolist()
                sp.user_playlist_add_tracks(user_id, playlist['id'], track_uris)

                st.balloons()
                st.success(f"Playlist '{playlist['name']}' created successfully!")
                st.link_button("Open in Spotify", playlist['external_urls']['spotify'])
            except Exception as e:
                st.error(f"Failed to create playlist: {e}")
